const PDFDocument = require('pdfkit');

const INK = '#1B2A4A';
const GOLD = '#C08A2E';
const LINE = '#DDD6C4';
const TEXT_SOFT = '#5B5F73';
const PAPER = '#FAF8F2';

/**
 * Draws one employee's payslip onto whatever page is currently active in doc.
 * Shared by both the single-payslip and combined multi-page functions below.
 */
function drawPayslipContent(doc, data) {
    const pageWidth = doc.page.width;
    const margin = 50;
    const contentWidth = pageWidth - margin * 2;

    // --- Header band ---
    doc.rect(0, 0, pageWidth, 110).fill(INK);
    doc.fillColor('#FFFFFF').font('Helvetica-Bold').fontSize(20)
        .text(data.companyName, margin, 32);
    doc.font('Helvetica').fontSize(9).fillColor('#B8C2DE')
        .text(`KRA PIN: ${data.companyPin}`, margin, 60);
    doc.font('Helvetica-Bold').fontSize(11).fillColor(GOLD)
        .text('PAYSLIP', pageWidth - margin - 120, 32, { width: 120, align: 'right' });
    doc.font('Helvetica').fontSize(9).fillColor('#B8C2DE')
        .text(`Period: ${data.month}/${data.year}`, pageWidth - margin - 120, 50, { width: 120, align: 'right' });

    let y = 140;

    // --- Employee name block ---
    doc.fillColor('#000').font('Helvetica-Bold').fontSize(15).text(data.employeeName, margin, y);
    y += 30;

    doc.moveTo(margin, y).lineTo(pageWidth - margin, y).strokeColor(LINE).lineWidth(1).stroke();
    y += 20;

    const colLabelX = margin + 12;
    const colValueW = 130;
    const colValueX = pageWidth - margin - colValueW - 12;

    function sectionHeader(label) {
        doc.rect(margin, y, contentWidth, 22).fill(PAPER);
        doc.fillColor(TEXT_SOFT).font('Helvetica-Bold').fontSize(9)
            .text(label.toUpperCase(), colLabelX, y + 6);
        y += 22;
    }

    function tableRow(label, value, options = {}) {
        const { bold = false, negative = false } = options;
        const rowH = 24;
        doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(10.5).fillColor('#000')
            .text(label, colLabelX, y + 6, { width: 260 });
        const displayValue = `${negative ? '-' : ''}KES ${Number(value).toLocaleString('en-KE', { minimumFractionDigits: 2 })}`;
        doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(10.5)
            .fillColor(negative ? '#B5482A' : '#000')
            .text(displayValue, colValueX, y + 6, { width: colValueW, align: 'right' });
        doc.moveTo(margin, y + rowH).lineTo(pageWidth - margin, y + rowH).strokeColor(LINE).lineWidth(0.5).stroke();
        y += rowH;
    }

    sectionHeader('Earnings');
    tableRow('Basic salary', data.basicPay);
    tableRow('Gross pay', data.grossPay, { bold: true });

    y += 10;
    sectionHeader('Deductions');
    tableRow('PAYE', data.paye, { negative: true });
    tableRow('NSSF', data.nssf, { negative: true });
    tableRow('SHIF', data.shif, { negative: true });
    tableRow('Housing Levy', data.housingLevy, { negative: true });

    y += 16;

    // --- Net pay highlight box ---
    doc.rect(margin, y, contentWidth, 44).fill(INK);
    doc.fillColor('#FFFFFF').font('Helvetica-Bold').fontSize(12)
        .text('NET PAY', colLabelX, y + 14);
    doc.font('Helvetica-Bold').fontSize(16).fillColor(GOLD)
        .text(`KES ${Number(data.netPay).toLocaleString('en-KE', { minimumFractionDigits: 2 })}`,
            colValueX - 40, y + 11, { width: colValueW + 40, align: 'right' });

    // --- Footer ---
    doc.font('Helvetica').fontSize(8).fillColor(TEXT_SOFT)
        .text('Generated by Zuvy Payroll — this is a computer-generated document.',
            margin, doc.page.height - 50, { width: contentWidth, align: 'center' });
}

/**
 * Builds a single employee's payslip as a PDF buffer.
 */
function generatePayslipPdf(data) {
    return new Promise((resolve, reject) => {
        const doc = new PDFDocument({ size: 'A4', margin: 50 });
        const chunks = [];
        doc.on('data', (chunk) => chunks.push(chunk));
        doc.on('end', () => resolve(Buffer.concat(chunks)));
        doc.on('error', reject);
        drawPayslipContent(doc, data);
        doc.end();
    });
}

/**
 * Builds ONE combined PDF with every employee's payslip as its own page.
 */
function generateCombinedPayslipsPdf(dataList) {
    return new Promise((resolve, reject) => {
        const doc = new PDFDocument({ size: 'A4', margin: 50 });
        const chunks = [];
        doc.on('data', (chunk) => chunks.push(chunk));
        doc.on('end', () => resolve(Buffer.concat(chunks)));
        doc.on('error', reject);

        dataList.forEach((data, index) => {
            if (index > 0) doc.addPage();
            drawPayslipContent(doc, data);
        });

        doc.end();
    });
}

module.exports = { generatePayslipPdf, generateCombinedPayslipsPdf };